export function parseSmokeShardArg(raw: string | undefined): SmokeShard | undefined {
  if (!raw) return undefined;
  const match = raw.match(/^([1-6])(?:\/\d+)?$/);
  if (!match) throw new Error(`Invalid smoke shard: ${raw}`);
  return Number(match[1]) as SmokeShard;
}
