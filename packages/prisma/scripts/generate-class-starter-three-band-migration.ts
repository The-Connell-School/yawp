/**
 * Generates SQL that adds the three-band Class Starter rubric (Excellent /
 * Partial Credit / No Credit) to the rubric library, with revision 1 recorded
 * as its current revision so assignments created after an admin selects it
 * pin to it. Inserts only when missing; never updates an existing rubric and
 * never changes which rubric any assignment type uses.
 *
 *   bun run scripts/generate-class-starter-three-band-migration.ts
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  CLASS_STARTER_THREE_BAND_RUBRIC_NAME,
  CLASS_STARTER_THREE_BAND_SCHEMA,
} from '../../../services/web-app/app/domain/assignment-types/class-starter-three-band-rubric';

function sqlLiteral(value: string) {
  return `'${value.replace(/'/g, "''")}'`;
}

const name = sqlLiteral(CLASS_STARTER_THREE_BAND_RUBRIC_NAME);
const title = sqlLiteral(CLASS_STARTER_THREE_BAND_SCHEMA.title);
const schema = sqlLiteral(JSON.stringify(CLASS_STARTER_THREE_BAND_SCHEMA));

const sql = `-- Adds the three-band Class Starter rubric (Excellent / Partial Credit /
-- No Credit) to the rubric library with revision 1 as its current revision.
-- Inserts only when missing. Never updates an existing rubric, and never
-- changes which rubric any assignment type uses: an admin selects it for
-- Class Starter in Admin → Assignment Types.
-- Generated by packages/prisma/scripts/generate-class-starter-three-band-migration.ts
SET lock_timeout = '5s';

DO $$
DECLARE
  schema_json JSONB := ${schema}::jsonb;
  revision_id TEXT := gen_random_uuid()::text;
  fp TEXT;
BEGIN
  IF EXISTS (SELECT 1 FROM "Rubric" WHERE "name" = ${name}) THEN
    RETURN;
  END IF;

  fp := encode(sha256(convert_to(canonical_json(schema_json), 'UTF8')), 'hex');

  IF NOT EXISTS (
    SELECT 1 FROM "RubricRevision" WHERE "rubricName" = ${name}
  ) THEN
    INSERT INTO "RubricRevision" (
      "id", "rubricName", "version", "schemaJson", "fingerprint",
      "requestId", "requestHash", "createdBy", "reason"
    ) VALUES (
      revision_id, ${name}, 1, schema_json, fp,
      'class-starter-three-band-v1', fp,
      'migration-class-starter-three-band',
      'Class Starter on three bands: Excellent / Partial Credit / No Credit'
    );
  ELSE
    SELECT "id" INTO revision_id
    FROM "RubricRevision"
    WHERE "rubricName" = ${name}
    ORDER BY "version" DESC
    LIMIT 1;
  END IF;

  INSERT INTO "Rubric" (
    "id", "createdAt", "updatedAt", "name", "title", "schemaJson", "currentRevisionId"
  ) VALUES (
    gen_random_uuid()::text, NOW(), NOW(), ${name}, ${title}, schema_json, revision_id
  );
END $$;
`;

const target = path.resolve(
  import.meta.dir,
  '../migrations/20261101120000_class_starter_three_band_rubric/migration.sql'
);
writeFileSync(target, sql);
console.log(`Wrote ${target}`);
